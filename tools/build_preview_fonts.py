"""Cut the shipped faces down to what a preview page needs.

A released face carries every Hangul syllable and its hinting, which comes to
2.6 MB as woff2 and is far more than a page should pull before it can show
anything. Two things shrink it. Dropping the hinting, which a browser at
preview sizes does not use, takes a face to 1.3 MB. Splitting Latin from
Hangul takes the Latin alone to 160 KB.

The split is what makes the page quick rather than merely smaller. Each half
is declared with its own `unicode-range`, so a browser fetches the Hangul of a
weight only when it has Hangul of that weight to draw, and fetches nothing at
all for the eight weights nobody has asked to see. Declaring all nine costs
one request each for the Latin and nothing more until a reader moves the
slider.

Every OpenType feature is kept. The stylistic sets and character variants are
the thing this font has that the alternatives do not, so the page has to be
able to switch them on.
"""

from __future__ import annotations

import argparse
import json
import sys
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import uharfbuzz as hb
from fontTools.subset import main as pyftsubset
from fontTools.ttLib import TTFont

from font_utils import PRESEVKA_VERSION, PRESEVKA_WEIGHTS

ROOT = Path(__file__).resolve().parents[1]

# What a reader can type, minus Hangul: ASCII, Latin-1, the punctuation and
# arrows a specimen shows, and the maths a code sample runs into.
LATIN_RANGES = (
    "U+0020-007E,U+00A0-00FF,U+0100-017F,U+2000-206F,U+2070-209F,"
    "U+20A0-20BF,U+2100-214F,U+2190-21FF,U+2200-22FF,U+2300-23FF,"
    "U+25A0-25FF,U+2600-26FF,U+FB00-FB06"
)

# Hangul syllables, the compatibility jamo a keyboard produces on its own, and
# the fullwidth forms that turn up in Korean text.
HANGUL_RANGES = "U+1100-11FF,U+3000-303F,U+3130-318F,U+A960-A97F,U+AC00-D7A3,U+FF00-FFEF"

PARTS = {"latin": LATIN_RANGES, "hangul": HANGUL_RANGES}

# The nine-weight table shows every weight at once, which would otherwise pull
# every weight's Hangul before a reader has asked for any of it. It needs one
# line, so it gets a face cut to that line's characters and nothing else.
SPECIMEN = "float Fox.quick(h){ is_brown } // 다람쥐 헌 쳇바퀴에 타고파"

# The glyph table on the page shows what a stylistic set actually changes,
# which is a question a reader cannot answer by eye across ninety characters.
# Iosevka's sets only ever touch the Latin side, so the table is Latin.
TABLE = (
    "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    "abcdefghijklmnopqrstuvwxyz"
    "0123456789"
    "!\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~"
)

# Every stylistic set Iosevka ships. There is no ss19.
FEATURES = [f"ss{n:02d}" for n in range(1, 21) if n != 19]


# What a @font-face declares, which is not what the file holds. The subsetting
# ranges above say which characters were kept; these say which characters the
# browser should come to this file for, and they are deliberately wider: a
# reader who types a character no face carries should get the fallback, not a
# second request. Latin takes everything outside the Hangul blocks.
CSS_LATIN_RANGE = "U+0000-2FFF,U+A000-ABFF,U+D800-FFFF"
CSS_HANGUL_RANGE = "U+1100-11FF,U+3000-318F,U+A960-A97F,U+AC00-D7A3,U+FF00-FFEF"

CSS_WEIGHTS = {
    "Thin": 100, "ExtraLight": 200, "Light": 300, "Regular": 400,
    "Medium": 500, "SemiBold": 600, "Bold": 700, "ExtraBold": 800,
    "Black": 900,
}

CSS_HEAD = """\
/* Presevka {version} \u2014 https://oqoz.github.io/presevka/

   This stylesheet always serves the latest release. A new one changes the
   letterforms, so pin a version by self-hosting the release archive.

   Generated by tools/build_preview_fonts.py; do not edit.
   SIL Open Font License 1.1. */
"""


def stylesheet(version: str) -> str:
    """Return the @font-face set a page needs to use these files.

    The page carries the same declarations, so writing them here and letting
    the page link this file keeps one copy rather than two that drift. The
    rules are the whole of what a stranger needs, which is why this is a file
    of its own rather than a block inside the page.
    """
    lines = [CSS_HEAD.format(version=version)]
    for weight, css in CSS_WEIGHTS.items():
        for part, rng in (("latin", CSS_LATIN_RANGE), ("hangul", CSS_HANGUL_RANGE)):
            lines.append(
                f"@font-face{{font-family:Presevka;font-weight:{css};"
                f"font-display:swap;src:url(fonts/Presevka-{weight}.{part}.woff2)"
                f'format("woff2");unicode-range:{rng}}}'
            )
    lines.append("")
    lines.append("/* The italic is Latin only: this font never slants its Hangul, so the")
    lines.append("   upright face's syllables are the same outlines, not a substitute. */")
    for weight, css in CSS_WEIGHTS.items():
        stem = "Italic" if weight == "Regular" else f"{weight}Italic"
        lines.append(
            f"@font-face{{font-family:Presevka;font-style:italic;font-weight:{css};"
            f"font-display:swap;src:url(fonts/Presevka-{stem}.latin.woff2)"
            f'format("woff2");unicode-range:{CSS_LATIN_RANGE}}}'
        )
    return "\n".join(lines) + "\n"


def changed_by(path: Path) -> dict[str, str]:
    """Return, per feature, the characters whose glyph it swaps.

    Asking the font is the only way to know. Shaping each character once plain
    and once with the feature on and comparing the glyph it lands on is exact,
    and it costs nothing at page load because the answer ships as data.
    """
    font = hb.Font(hb.Face(hb.Blob.from_file_path(str(path))))

    def glyphs(text: str, feature: str | None) -> list[int]:
        buf = hb.Buffer()
        buf.add_str(text)
        buf.guess_segment_properties()
        hb.shape(font, buf, {feature: True} if feature else {})
        return [info.codepoint for info in buf.glyph_infos]

    plain = {ch: glyphs(ch, None) for ch in TABLE}
    out = {}
    for feature in FEATURES:
        hit = "".join(ch for ch in TABLE if glyphs(ch, feature) != plain[ch])
        if hit:
            out[feature] = hit
    return out


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--font-dir", type=Path, default=ROOT / "dist")
    p.add_argument("--output-dir", type=Path, default=ROOT / "site" / "fonts")
    p.add_argument(
        "--slopes",
        default="Upright",
        help="쉼표로 구분. Upright,Italic 처럼 주면 이탤릭도 만듭니다.",
    )
    return p.parse_args()


def cut(source: Path, target: Path, unicodes: str | None, text: str = "") -> int:
    target.parent.mkdir(parents=True, exist_ok=True)
    argv = sys.argv
    sys.argv = [
        "pyftsubset",
        str(source),
        f"--text={text}" if text else f"--unicodes={unicodes}",
        # Keep every feature: the stylistic sets are the point.
        "--layout-features=*",
        "--flavor=woff2",
        "--desubroutinize",
        f"--output-file={target}",
    ]
    try:
        pyftsubset()
    finally:
        sys.argv = argv
    return target.stat().st_size


def one_face(args: tuple[Path, Path, str, bool]) -> tuple[str, int, str]:
    """Cut the parts a single face needs. Runs in its own process.

    An italic face is cut to its Latin only. This font never slants its
    Hangul, so an italic face's syllables are the upright ones to the point:
    every one of the four hundred checked is an identical outline. Letting the
    upright face serve them is not a fallback, it is the same glyph, and it
    saves a megabyte a weight and a third of the build.
    """
    source, out_dir, stem, italic = args
    total = 0
    line = [f"{stem:18}"]
    for part, unicodes in PARTS.items():
        if italic and part == "hangul":
            continue
        size = cut(source, out_dir / f"Presevka-{stem}.{part}.woff2", unicodes)
        total += size
        line.append(f"{part} {size / 1024:7.1f} KB")
    if not italic:
        # The weight table is upright, so only upright needs its one line.
        size = cut(source, out_dir / f"Presevka-{stem}.spec.woff2", None, SPECIMEN)
        total += size
        line.append(f"spec {size / 1024:5.1f} KB")
    return stem, total, "  ".join(line)


def main() -> None:
    args = parse_args()
    slopes = [s.strip() for s in args.slopes.split(",") if s.strip()]

    jobs = []
    for weight in PRESEVKA_WEIGHTS:
        for slope in slopes:
            stem = weight if slope == "Upright" else f"{weight}Italic"
            stem = stem.replace("RegularItalic", "Italic")
            # A local build leaves TTFs behind; a release ships woff2, and
            # pyftsubset reads either.
            source = next(
                (
                    c
                    for c in (
                        args.font_dir / f"Presevka-{stem}.ttf",
                        args.font_dir / f"Presevka-{stem}.woff2",
                    )
                    if c.is_file()
                ),
                None,
            )
            if source is None:
                raise SystemExit(f"no Presevka-{stem}.ttf or .woff2 in {args.font_dir}")
            jobs.append((source, args.output_dir, stem, slope == "Italic"))

    # Eighteen faces times three cuts is half an hour on a two-core runner when
    # it is done one after another, and every cut is independent of the rest.
    args.output_dir.mkdir(parents=True, exist_ok=True)
    total = 0
    with ProcessPoolExecutor() as pool:
        for _, size, line in pool.map(one_face, jobs):
            total += size
            print(line, flush=True)
    print(f"\n{args.output_dir}: {total / 1048576:.1f} MB")

    regular = next(
        c
        for c in (
            args.font_dir / "Presevka-Regular.ttf",
            args.font_dir / "Presevka-Regular.woff2",
        )
        if c.is_file()
    )
    if regular.suffix == ".woff2":
        # HarfBuzz does not read woff2; hand it the decompressed table.
        plain = args.output_dir / "_regular.ttf"
        tt = TTFont(regular)
        tt.flavor = None
        tt.save(plain)
        tt.close()
        regular = plain
    # The page offers a download, so a version it states has to be the one it
    # would actually hand over. The build fills it rather than the markup
    # carrying a number that goes stale on the next release.
    table = {
        "version": PRESEVKA_VERSION,
        "characters": TABLE,
        "changes": changed_by(regular),
    }
    if regular.name == "_regular.ttf":
        regular.unlink()
    # A script tag rather than a fetch: the grid is then built before first
    # paint instead of appearing a moment later, and the page keeps working
    # from a file:// checkout where fetch would be blocked.
    target = args.output_dir.parent / "glyph-variants.js"
    target.write_text(
        "window.PRESEVKA_GLYPHS=" + json.dumps(table, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )
    counts = ", ".join(f"{k} {len(v)}" for k, v in table["changes"].items())
    print(f"{target}: {counts}")

    sheet = args.output_dir.parent / "presevka.css"
    sheet.write_text(stylesheet(PRESEVKA_VERSION), encoding="utf-8")
    print(f"{sheet}: {sheet.stat().st_size / 1024:.1f} KB")


if __name__ == "__main__":
    main()
